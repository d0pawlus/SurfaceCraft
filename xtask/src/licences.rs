//! `cargo xtask licences [--check]`: every dependency's licence is on the allowlist (never
//! GPL/LGPL/AGPL), and THIRD-PARTY-LICENSES.txt is regenerated (with `--check`: must be current).
use serde_json::Value;
use std::process::Command;

/// Accepted SPDX identifiers.
const ALLOW: &[&str] = &[
    "MIT",
    "MIT-0",
    "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "0BSD",
    "ISC",
    "Zlib",
    "Unicode-3.0",
    "Unicode-DFS-2016",
    "CC0-1.0",
    "BSL-1.0",
    "OFL-1.1",
    "Ubuntu-font-1.0",
    "CDLA-Permissive-2.0",
    "BlueOak-1.0.0",
    "Unlicense",
];

/// Packages without a `license` field, checked by hand (name, licence).
const KNOWN: &[(&str, &str)] = &[];

fn accepted(expr: &str) -> bool {
    // OR binds loosest, then AND; parentheses are flattened (good enough for crates.io data)
    let e = expr.replace(['(', ')'], " ").replace('/', " OR ");
    e.split(" OR ").any(|alt| {
        alt.split(" AND ").all(|term| {
            let t = term.split_whitespace().collect::<Vec<_>>().join(" ");
            ALLOW.contains(&t.as_str())
        })
    })
}

pub(crate) fn run(check: bool) -> Result<(), String> {
    eprintln!("==> licences");
    let out = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .current_dir(crate::root())
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()
        .map_err(|e| format!("cargo metadata: {e}"))?;
    if !out.status.success() {
        return Err(format!("cargo metadata failed: {}", String::from_utf8_lossy(&out.stderr)));
    }
    let meta: Value = serde_json::from_slice(&out.stdout).map_err(|e| format!("cargo metadata output: {e}"))?;
    let members: Vec<&str> =
        meta["workspace_members"].as_array().into_iter().flatten().filter_map(Value::as_str).collect();
    let mut rows = Vec::new();
    let mut errors = Vec::new();
    for pkg in meta["packages"].as_array().into_iter().flatten() {
        let id = pkg["id"].as_str().unwrap_or("");
        if members.contains(&id) {
            continue;
        }
        let name = pkg["name"].as_str().unwrap_or("?");
        let version = pkg["version"].as_str().unwrap_or("?");
        let lic = pkg["license"]
            .as_str()
            .map(str::to_string)
            .or_else(|| KNOWN.iter().find(|(n, _)| *n == name).map(|(_, l)| (*l).to_string()));
        let repo = pkg["repository"].as_str().unwrap_or("");
        match lic {
            Some(l) if accepted(&l) => rows.push(format!("{name} {version}\n    licence: {l}\n    source: {repo}\n")),
            Some(l) => errors.push(format!("{name} {version}: licence `{l}` is not on the allowlist")),
            None => errors.push(format!("{name} {version}: no licence field (add it to KNOWN after checking)")),
        }
    }
    rows.sort();
    rows.dedup();
    if !errors.is_empty() {
        return Err(errors.join("\n"));
    }
    let text = format!(
        "THIRD-PARTY LICENSES\n====================\n\nGenerated by `cargo xtask licences`; do not edit by hand.\nEvery dependency of SurfaceCraft (all targets) and its licence.\n\n{}",
        rows.join("\n")
    );
    let path = crate::root().join("THIRD-PARTY-LICENSES.txt");
    let current = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
    if current != text {
        if check {
            std::fs::write(&path, &text).map_err(|e| format!("write {}: {e}", path.display()))?;
            return Err("THIRD-PARTY-LICENSES.txt was out of date; it has been regenerated, commit it".into());
        }
        std::fs::write(&path, &text).map_err(|e| format!("write {}: {e}", path.display()))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::accepted;

    #[test]
    fn expressions() {
        assert!(accepted("MIT OR Apache-2.0"));
        assert!(accepted("MIT/Apache-2.0"));
        assert!(accepted("(MIT OR Apache-2.0) AND Unicode-3.0"));
        assert!(accepted("Apache-2.0 WITH LLVM-exception OR MIT"));
        assert!(!accepted("GPL-3.0"));
        assert!(!accepted("LGPL-2.1 OR GPL-2.0"));
        assert!(accepted("MIT OR GPL-3.0"));
        assert!(!accepted("MIT AND GPL-3.0"));
    }
}
